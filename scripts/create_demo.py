"""Create original demo cards and es-MX narration using installed Windows voices."""
import json
import os
from pathlib import Path
import subprocess
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]
ENGINE_PYTHON = ROOT / "engines/MoneyPrinterTurbo/.venv/Scripts/python.exe"
SCRIPT = (
    "Este es el primer video de VideosIA. La narración y las imágenes se crean "
    "en este equipo, sin enviar el guion a un proveedor de voz. El resultado "
    "pasa una revisión técnica y queda pendiente de revisión humana antes de publicarse."
)


def main():
    if os.name != "nt":
        raise SystemExit("El generador de demo usa voces Windows. En otros sistemas aporta tu WAV y PNG en inputs/.")
    if not ENGINE_PYTHON.is_file():
        raise SystemExit("Falta el entorno del motor. Ejecuta scripts/setup.ps1 primero.")
    if Path(sys.executable).resolve() != ENGINE_PYTHON.resolve():
        return subprocess.call([str(ENGINE_PYTHON), str(Path(__file__).resolve())], cwd=ROOT)
    from PIL import Image, ImageDraw, ImageFont

    destination = ROOT / "inputs/demo"
    destination.mkdir(parents=True, exist_ok=True)
    font = Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts/arial.ttf"
    if not font.is_file():
        raise SystemExit("Falta la fuente Arial instalada en Windows.")
    title_font = ImageFont.truetype(str(font), 86)
    body_font = ImageFont.truetype(str(font), 43)
    label_font = ImageFont.truetype(str(font), 28)
    scenes = [
        ("PRIMER RENDER", "VideosIA", "Del guion al video\ncon recursos locales", "01"),
        ("PROCESO LOCAL", "Tu equipo.\nTus archivos.", "Voz instalada en Windows\nImágenes propias\nSin proveedor de voz remoto", "02"),
        ("REVISIÓN HUMANA", "Crear.\nComprobar.\nRevisar.", "El QA técnico no autoriza\nla publicación del video", "03"),
    ]
    for index, (label, title, body, number) in enumerate(scenes, 1):
        image = Image.new("RGB", (1080, 1920), "#101b2b")
        draw = ImageDraw.Draw(image)
        draw.rectangle((80, 120, 1000, 128), fill="#60dfbc")
        draw.text((80, 180), "VIDEOSIA / LABORATORIO LOCAL", font=label_font, fill="#b2c5d8")
        draw.text((80, 480), label, font=label_font, fill="#60dfbc")
        draw.multiline_text((75, 560), title, font=title_font, fill="#f4f8fc", spacing=24)
        draw.multiline_text((80, 1030), body, font=body_font, fill="#c4d4e4", spacing=28)
        draw.text((80, 1710), "DEMOSTRACIÓN · PENDIENTE DE REVISIÓN", font=label_font, fill="#b2c5d8")
        draw.text((905, 1700), number, font=body_font, fill="#60dfbc")
        image.save(destination / f"card-{index}.png")

    script_path = destination / "script.txt"
    script_path.write_text(SCRIPT, encoding="utf-8")
    speech_command = r'''
Add-Type -AssemblyName System.Speech
$synthesizer = New-Object System.Speech.Synthesis.SpeechSynthesizer
try {
    $voices = @($synthesizer.GetInstalledVoices() | Where-Object { $_.Enabled -and $_.VoiceInfo.Culture.Name -eq 'es-MX' })
    if ($voices.Count -eq 0) { throw 'Falta una voz local es-MX instalada' }
    $synthesizer.SelectVoice($voices[0].VoiceInfo.Name)
    $synthesizer.Rate = 0
    $synthesizer.SetOutputToWaveFile($env:VIDEOSIA_DEMO_WAV)
    $text = [IO.File]::ReadAllText($env:VIDEOSIA_DEMO_TEXT, [Text.Encoding]::UTF8)
    $synthesizer.Speak($text)
    Write-Output $voices[0].VoiceInfo.Name
} finally { $synthesizer.Dispose() }
'''
    env = dict(os.environ, VIDEOSIA_DEMO_TEXT=str(script_path),
               VIDEOSIA_DEMO_WAV=str(destination / "narration.wav"))
    powershell = Path(os.environ.get("SYSTEMROOT", "C:/Windows")) / "System32/WindowsPowerShell/v1.0/powershell.exe"
    speech = subprocess.run([str(powershell), "-NoProfile", "-NonInteractive", "-Command", speech_command],
                            env=env, capture_output=True, text=True, timeout=90)
    if speech.returncode:
        raise SystemExit("No se pudo generar la narración con la voz local instalada.")
    with wave.open(str(destination / "narration.wav")) as audio:
        duration = audio.getnframes() / audio.getframerate()
    provenance = {"visuals": "Original cards generated by VideosIA with installed Arial font",
                  "narration": "Windows System.Speech installed es-MX voice", "voice": speech.stdout.strip(),
                  "duration_seconds": duration, "cloud_provider_used": False,
                  "subtitles": "not generated", "publication_allowed": False}
    (destination / "provenance.json").write_text(json.dumps(provenance, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({"assets": str(destination), "duration_seconds": duration, "voice": provenance["voice"]}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
